////////////////////////////////////////////////////////////////////////////////////////////////////
//	Name:			Match_Check
//	Function:		Check match type
//	Argument:		ST_MATCH_DATA* apst_Match: Pointer to match data structure
//
//	Return value:	None
//	Create:			2025.10.09	V.Vu New
//	Change:			-
//	Remarks:		-
////////////////////////////////////////////////////////////////////////////////////////////////////
void Match_Check(const ST_MATCH_DATA* apst_Match)
{
    switch (apst_Match->u1_MatchType)
    {
        case U1_MATCH_TYPE_U1:
            MATCH_FUNC(U1);
            break;
        case U1_MATCH_TYPE_U2:
            MATCH_FUNC(U2);
            break;
        case U1_MATCH_TYPE_S1:
            MATCH_FUNC(S1);
            break;
        case U1_MATCH_TYPE_S2:
            MATCH_FUNC(S2);
            break;
        default:
            break;
    }
}