#define MATCH_FUNC(TYPE)                                                  \
    if (*(TYPE*)apst_Match->vp_BefData == *(TYPE*)apst_Match->vp_NewData) \
    {                                                                     \
        if (*(apst_Match->pu1_MatchCnt) < apst_Match->u1_MatchCntRef)     \
            (*(apst_Match->pu1_MatchCnt))++;                              \
        if (*(apst_Match->pu1_MatchCnt) >= apst_Match->u1_MatchCntRef)    \
            *(TYPE*)apst_Match->vp_Data = *(TYPE*)apst_Match->vp_NewData; \
    }                                                                     \
    else                                                                  \
    {                                                                     \
        *(apst_Match->pu1_MatchCnt) = 1;                                  \
    }                                                                     \
    *(TYPE*)apst_Match->vp_BefData = *(TYPE*)apst_Match->vp_NewData;
